#!/usr/bin/env node
// Build a content-hash manifest for /public assets that need cache-busting.
//
// Why this exists: static-export deployments serve /public/* verbatim with
// long-lived caches. If you ship a same-name v2 of a WebP or Unity build
// file, users see the cached v1 for a day. This script hashes those files
// and writes src/config/asset-manifest.ts, which the app reads through
// `assetUrl()` to get URLs like `/Foo.webp?v=ab12cd34`. When the file
// content changes the hash changes, the URL changes, the cache busts.
//
// What gets hashed:
//   • Every /public/*.webp
//   • Every /public/UnityGames/<game>/{WebGL_build.loader.js,
//     WebGL_build.data[.unityweb], WebGL_build.framework.js[.unityweb],
//     WebGL_build.wasm[.unityweb]}
//   • Logo SVGs and favicons (so brand updates also bust caches)
//
// Anything not in the manifest falls through to the raw URL. New file
// types can be added by extending GLOBS below.
//
// Wiring:
//   • `npm run build` runs this first via the `prebuild` hook.
//   • CI also runs it explicitly so failures surface there.
//   • Generated file is checked in so dev builds and editor type-checks
//     see the latest hashes without re-running the script.

import { createHash } from "node:crypto";
import { readFile, writeFile, readdir, stat } from "node:fs/promises";
import { resolve, relative, join } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const PUBLIC_DIR = resolve(ROOT, "public");
const OUT = resolve(ROOT, "src/config/asset-manifest.ts");

const GLOBS = [
  // Top-level WebP thumbnails used by Knowledge Gallery cards + heroes.
  { dir: PUBLIC_DIR, recursive: false, ext: [".webp"] },
  // Logo SVGs + favicons referenced from brand config.
  { dir: PUBLIC_DIR, recursive: false, ext: [".svg", ".ico", ".png"] },
  // Unity WebGL builds — all four manifests per game.
  {
    dir: resolve(PUBLIC_DIR, "UnityGames"),
    recursive: true,
    ext: [".js", ".unityweb"],
  },
];

async function* walk(dir, recursive) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (recursive) yield* walk(p, true);
    } else if (e.isFile()) {
      yield p;
    }
  }
}

async function collect() {
  const files = new Set();
  for (const g of GLOBS) {
    for await (const f of walk(g.dir, g.recursive)) {
      if (g.ext.some((ext) => f.endsWith(ext))) files.add(f);
    }
  }
  return [...files].sort();
}

async function hashFile(p) {
  const buf = await readFile(p);
  return createHash("sha256").update(buf).digest("hex").slice(0, 10);
}

function toPublicUrl(absPath) {
  // /Volumes/.../public/Foo.webp -> /Foo.webp
  // /Volumes/.../public/UnityGames/x/y.js -> /UnityGames/x/y.js
  return "/" + relative(PUBLIC_DIR, absPath).split("\\").join("/");
}

const files = await collect();
const entries = await Promise.all(
  files.map(async (f) => [toPublicUrl(f), await hashFile(f)]),
);

const sorted = entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const lines = [
  "// AUTO-GENERATED by scripts/build-asset-manifest.mjs",
  "// Edit the script, not this file. Re-runs on every `npm run build`.",
  "//",
  "// Maps `/public/*` paths to 10-character content hashes. Consumers go",
  "// through `assetUrl()` to get a cache-busted URL like `/Foo.webp?v=abcd`.",
  "// Paths not in the manifest fall through to the raw URL.",
  "",
  "export const ASSET_HASHES: Readonly<Record<string, string>> = {",
  ...sorted.map(([url, hash]) => `  ${JSON.stringify(url)}: ${JSON.stringify(hash)},`),
  "} as const;",
  "",
  "/**",
  " * Resolve a `/public/*` path to its cache-busted URL. Unknown paths fall",
  " * through unchanged so dev/local references don't break when an asset",
  " * hasn't been hashed yet (or is intentionally not under /public).",
  " */",
  "export function assetUrl(path: string): string {",
  "  const hash = ASSET_HASHES[path];",
  "  return hash ? `${path}?v=${hash}` : path;",
  "}",
  "",
];

await writeFile(OUT, lines.join("\n"), "utf8");
console.log(`asset-manifest: ${sorted.length} files hashed → ${relative(ROOT, OUT)}`);
